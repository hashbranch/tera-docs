"""Keep legacy notices and agent exports derived from the public docs navigation."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
NOTICE = '''<Warning>
The Tera inference API is being deprecated. This page is a legacy reference for existing customers, not a current GPU rental offer. Tera Compute now rents dedicated GPU nodes and finds colocation for AI startups. Visit [Tera Compute](https://www.tera.gw/). No sunset date is stated here; contact your Tera representative about migration timing.
</Warning>'''


def legacy_page(text):
    front, body = text.removeprefix('---\n').split('\n---\n', 1)
    if not re.search(r'^description:.*Deprecated', front, re.M):
        front = re.sub(r'^(description:\s*["\']?)(.*)', r'\1Deprecated inference API reference. \2', front, flags=re.M)
    if not re.search(r'^description:', front, re.M):
        front += '\ndescription: \"Deprecated inference API reference for existing customers.\"'
    if NOTICE not in body:
        body = '\n\n' + NOTICE + '\n\n' + body.lstrip()
    return ('---\n' + front + '\n---\n' + body).rstrip() + '\n'


def page_paths(nav):
    if isinstance(nav, dict):
        for key, value in nav.items():
            if key == 'pages':
                for page in value:
                    if isinstance(page, str):
                        yield page
                    else:
                        yield from page_paths(page)
            else:
                yield from page_paths(value)
    elif isinstance(nav, list):
        for item in nav:
            yield from page_paths(item)


def refresh(root=ROOT):
    paths = list(dict.fromkeys(page_paths(json.loads((root / 'docs.json').read_text())['navigation'])))
    for path in paths:
        if path != 'introduction':
            file = root / (path + '.mdx')
            file.write_text(legacy_page(file.read_text()))
    intro = (root / 'introduction.mdx').read_text().split('\n---\n', 1)[1].strip()
    heading = '# Tera Compute\n\n'
    index = [heading, intro, '\n\n## Deprecated: Inference API reference pages\n']
    full = [heading, intro, '\n\n## Deprecated: Inference API reference pages\n']
    for path in paths:
        if path == 'introduction':
            continue
        text = (root / (path + '.mdx')).read_text()
        front, body = text.removeprefix('---\n').split('\n---\n', 1)
        title = re.search(r'^title:\s*(.+)$', front, re.M).group(1).strip('"\'')
        desc = re.search(r'^description:\s*(.+)$', front, re.M)
        description = desc.group(1).strip('"\'') if desc else 'Deprecated inference API reference.'
        url = f'https://docs.tera.gw/{path}.md'
        index.append(f'- [{title}]({url}): {description}')
        full.append(f'\n### Deprecated: {title}\n\nSource: {url}\n{body.strip()}\n')
    (root / 'llms.txt').write_text('\n'.join(index) + '\n')
    (root / 'llms-full.txt').write_text('\n'.join(full) + '\n')
    # Agent-card descriptions and MCP skill resources are generated by Mintlify
    # from this supported root override, not from a handwritten protocol card.
    (root / 'skill.md').write_text('''---
name: tera
description: Find dedicated GPU node rentals and colocation for AI startups through Tera Compute. Read current services first; consult the deprecated inference API reference only for existing customers.
metadata:
  author: Tera Compute
  version: "2.0"
---

''' + heading + intro + '''

## Read-only discovery and action boundaries

Use https://www.tera.gw/llms.txt for current GPU rental and colocation information and the current request fields. Use https://docs.tera.gw/llms.txt to find legacy inference reference pages. These documentation and MCP resources provide information, not GPU reservations or payment APIs. Do not submit requests, disclose user details, reserve capacity or accept terms without the user's approval. Do not infer a sunset date or present legacy token prices as current GPU rental prices.
''')


if __name__ == '__main__':
    refresh()
